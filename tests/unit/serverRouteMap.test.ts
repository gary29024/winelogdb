import { describe, expect, it } from 'vitest';
import cuveeApp from '../../worker/cuveeEntry';
import entryApp from '../../worker/entry';
import baseApp from '../../worker/index';
import layeredApp from '../../worker/layered';
import { researchRoutes } from '../../worker/researchQueueEntry';

// The API is served by Hono apps wrapped around each other. A request enters
// the outermost one and is handed inward until a layer answers it, and several
// addresses are declared by more than one layer, each adding to what the next
// one returns. This test writes down which layers declare which address, so the
// answer to "where is this handled?" is a table rather than a search through
// five files - and so that folding the layers into one cannot silently drop or
// add an address: the table changes, and the change shows up in review.
//
// Update the table after adding or moving a route:
//   npx vitest run tests/unit/serverRouteMap.test.ts -u
const layers = [
  { file: 'worker/researchQueueEntry.ts', routes: researchRoutes() },
  { file: 'worker/cuveeEntry.ts', routes: cuveeApp.routes },
  { file: 'worker/entry.ts', routes: entryApp.routes },
  { file: 'worker/layered.ts', routes: layeredApp.routes },
  { file: 'worker/index.ts', routes: baseApp.routes },
];
const METHOD_ORDER = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'];

function routeMap() {
  const declared = new Map<string, { method: string; path: string; files: string[] }>();
  for (const layer of layers) {
    for (const { method, path } of layer.routes) {
      // `ALL` is a layer's catch-all hand-off to the next one, or shared middleware; neither is an address.
      if (method === 'ALL') continue;
      const key = `${path} ${method}`;
      const entry = declared.get(key) ?? { method, path, files: [] };
      if (!entry.files.includes(layer.file)) entry.files.push(layer.file);
      declared.set(key, entry);
    }
  }
  return [...declared.values()].sort(
    (a, b) => a.path.localeCompare(b.path) || METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method),
  );
}

describe('server route map', () => {
  it('matches docs/server-routes.md', async () => {
    const routes = routeMap();
    const shared = routes.filter((route) => route.files.length > 1);
    const lines = [
      '# Server routes',
      '',
      'Generated by `tests/unit/serverRouteMap.test.ts`. Do not edit by hand; run',
      '`npx vitest run tests/unit/serverRouteMap.test.ts -u` after adding or moving a route.',
      '',
      'A request enters `worker/multiUserEntry.ts` (sign-in, permissions, AI credits), then',
      '`worker/structureEntry.ts`, then the layers below from the outside in. Where an address lists',
      'several files, the first one receives the request and calls the next, adding to its answer.',
      '',
      'Not listed: the routes `multiUserEntry.ts` and `structureEntry.ts` answer themselves',
      '(`/api/auth/*`, `/api/me`, `/api/credits*`, `/api/admin/*`, `/api/friends*`, `/api/shared/*`,',
      'catalogue corrections, group scans and Champagne extraction). Those are matched by hand in',
      'those two files and in `worker/multiUser/`.',
      '',
      `${routes.length} addresses, ${shared.length} of them declared by more than one layer.`,
      '',
      '| Method | Address | Declared in (outermost first) |',
      '| --- | --- | --- |',
      ...routes.map(
        (route) => `| ${route.method} | \`${route.path}\` | ${route.files.map((file) => `\`${file}\``).join(' → ')} |`,
      ),
      '',
    ];
    await expect(lines.join('\n')).toMatchFileSnapshot('../../docs/server-routes.md');
  });

  it('declares each address at most once per layer', () => {
    for (const layer of layers) {
      const seen = layer.routes
        .filter((route) => route.method !== 'ALL')
        .map((route) => `${route.method} ${route.path}`);
      const repeated = seen.filter((key, index) => seen.indexOf(key) !== index);
      expect(repeated, layer.file).toEqual([]);
    }
  });
});
